def build_draft_contracts(
    questions: list[dict[str, Any]],
    cleaned_files: list[Path],
    table_entries: list[dict[str, Any]],
    data_summary: dict[str, Any],
) -> tuple[dict[str, Any], dict[str, Any], dict[str, Any], dict[str, Any]]:
    result_items: list[dict[str, Any]] = []
    metric_items: list[dict[str, Any]] = []
    conclusion_items: list[dict[str, Any]] = []

    for index, question in enumerate(questions, start=1):
        qid = question_id(question, index)
        title = str(question.get("title") or f"问题{index}")
        task_type = str(question.get("task_type") or "综合建模/统计分析")
        main_model = str(question.get("main_model") or question.get("baseline_model") or "结合题目需求的主模型")
        result_items.append(
            {
                "question_id": qid,
                "title": title,
                "task_type": task_type,
                "result_type": result_type(task_type),
                "main_model": main_model,
                "baseline_model": question.get("baseline_model", ""),
                "result_summary": f"{title} 已生成结果证据契约草稿。当前建议主模型为“{main_model}”，真实数值、参数和方案需要结合当前赛题专用建模代码补齐。",
                "outputs": [],
                "parameters": [],
                "evidence_status": "needs_real_modeling",
                "status": "draft_contract",
            }
        )
        for metric in metric_templates(task_type):
            metric_items.append({"question_id": qid, "status": "to_be_filled", **metric})

        q_table_id = f"table_{qid.lower()}_result_skeleton"
        q_table_path = TABLES_DIR / f"{q_table_id}.csv"
        write_csv(q_table_path, question_table_rows({"question_id": qid, **question}))
        table_entries.append(
            {
                "table_id": q_table_id,
                "question_id": qid,
                "title": f"{title} 结果证据表骨架",
                "purpose": "列出本问应进入论文的结果表、指标表或敏感性表，供 Agent 二次填充真实结果。",
                "path": rel(q_table_path),
                "source": "paper_output/plan/model_route.json",
                "status": "draft_contract",
            }
        )
        conclusion_items.append(
            {
                "question_id": qid,
                "conclusion_text": f"{title} 的最终结论需要在真实建模结果补齐后回扣原问；当前已建立结果证据契约骨架。",
                "evidence_required": ["model_results.json", "metrics.json", "table_index.json"],
                "evidence_status": "needs_real_modeling",
            }
        )

    common = {
        "schema_version": "1.0",
        "generated_by": GENERATED_BY,
        "generated_at": now(),
    }
    model_results = {
        **common,
        "source": "paper_output/plan/model_route.json",
        "data_sources": [rel(path) for path in cleaned_files],
        "questions": result_items,
        "data_summary": data_summary,
    }
    metrics = {**common, "source": "paper_output/results/model_results.json", "items": metric_items}
    conclusions = {**common, "source": "paper_output/results/model_results.json", "items": conclusion_items}
    table_index = {
        **common,
        "source": "paper_output/results/model_results.json",
        "tables": table_entries,
        "notes": [
            "status=draft_contract 的表格是结果证据骨架，不应直接冒充最终比赛结果。",
            "真实赛题应由 Agent 根据当前建模代码补齐表格数值后再进入最终正文。",
        ],
    }
    return model_results, metrics, conclusions, table_index


def merge_with_existing(
    model_results: dict[str, Any],
    metrics: dict[str, Any],
    conclusions: dict[str, Any],
    table_index: dict[str, Any],
) -> tuple[dict[str, Any], dict[str, Any], dict[str, Any], dict[str, Any]]:
    existing_results = load_json(RESULTS_DIR / "model_results.json") or {}
    existing_metrics = load_json(RESULTS_DIR / "metrics.json") or {}
    existing_conclusions = load_json(RESULTS_DIR / "conclusions.json") or {}
    existing_tables = load_json(TABLES_DIR / "table_index.json") or {}

    model_results["questions"] = preserve_existing_by_question(
        existing_results.get("questions", []) if isinstance(existing_results.get("questions"), list) else [],
        model_results["questions"],
    )
    metrics["items"] = preserve_existing_by_question(
        existing_metrics.get("items", []) if isinstance(existing_metrics.get("items"), list) else [],
        metrics["items"],
    )
    conclusions["items"] = preserve_existing_by_question(
        existing_conclusions.get("items", []) if isinstance(existing_conclusions.get("items"), list) else [],
        conclusions["items"],
    )
    table_index["tables"] = preserve_existing_tables(
        existing_tables.get("tables", []) if isinstance(existing_tables.get("tables"), list) else [],
        table_index["tables"],
    )
    return model_results, metrics, conclusions, table_index


